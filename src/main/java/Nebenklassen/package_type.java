package Nebenklassen;

public class package_type {

	String desc;
	String count;
	
	public package_type(String desc, String count) {
		super();
		this.desc = desc;
		this.count = count;
	}

	public String getDesc() {
		return desc;
	}

	public void setDesc(String desc) {
		this.desc = desc;
	}

	public String getCount() {
		return count;
	}

	public void setCount(String count) {
		this.count = count;
	}
	
	
}
